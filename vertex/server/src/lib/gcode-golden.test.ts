import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { describe, expect, test } from "@rstest/core";
import { normalizeGcodeForCompare } from "../../../shared/slice-job";
import { sliceWithVertexSlice } from "./vertexslice-client";

const APEX_CORE_GOLDEN = "/workspace/slices/LOCKED/ApexCore_95A_GOLDEN_2026-10-31.gcode";
const APEX_CORE_SHA = "54af16eda2e11dbef354f594dd501afe799d45f3ee679819b2c65908aaef5324";
const APEX_LIGHT_GOLDEN = "/workspace/slices/LOCKED/ApexLight_90A_GOLDEN_2026-10-31.gcode";
const APEX_LIGHT_SHA = "3a0a54a2322e579e2c5cd4e003f061a86af61d49310115299ce6856628424e67";

function sha256(path: string): string {
    return createHash("sha256").update(readFileSync(path)).digest("hex");
}

describe("gcode golden normalization", () => {
    test("ignores generator and printing-object comments only", () => {
        const a = [
            "; generated by OrcaSlicer 2.3",
            "G1 X1",
            "; printing object Insole",
            "G1 X2",
            "; stop printing object Insole",
        ].join("\n");
        const b = [
            "; generated by VertexSlice",
            "G1 X1",
            "; printing object Other",
            "G1 X2",
            "; stop printing object Other",
        ].join("\n");
        expect(normalizeGcodeForCompare(a)).toBe(normalizeGcodeForCompare(b));
        expect(normalizeGcodeForCompare(a)).toContain("G1 X1");
        expect(normalizeGcodeForCompare("; TYPE:Wall\nG1 X3")).toContain("; TYPE:Wall");
    });

    test("live VertexSlice golden compare when staging and reference files exist", async () => {
        const corePresent = existsSync(APEX_CORE_GOLDEN);
        const lightPresent = existsSync(APEX_LIGHT_GOLDEN);
        const coreStl = [
            "/workspace/slices/LOCKED/ApexCore_95A.stl",
            "/workspace/slices/ApexCore_95A.stl",
            "/workspace/slices/reference/ApexCore_95A.stl",
        ].find((path) => existsSync(path));
        const lightStl = [
            "/workspace/slices/LOCKED/ApexLight_90A.stl",
            "/workspace/slices/ApexLight_90A.stl",
            "/workspace/slices/reference/ApexLight_90A.stl",
        ].find((path) => existsSync(path));
        const staging = Boolean(process.env.VERTEXSLICE_URL?.trim());
        if (corePresent) expect(sha256(APEX_CORE_GOLDEN)).toBe(APEX_CORE_SHA);
        if (lightPresent) expect(sha256(APEX_LIGHT_GOLDEN)).toBe(APEX_LIGHT_SHA);
        // Untested unless VERTEXSLICE_URL is set and the LOCKED goldens plus reference
        // STLs are on disk. This sandbox has neither, so no G-code is fetched or written.
        if (!staging || !corePresent || !lightPresent || !coreStl || !lightStl) return;

        const coreGcode = await sliceWithVertexSlice({
            stl: new Uint8Array(readFileSync(coreStl)),
            profileId: "apex-v2-insole-95a",
            material: "apex_core",
            fileName: "ApexCore_95A.stl",
        });
        const lightGcode = await sliceWithVertexSlice({
            stl: new Uint8Array(readFileSync(lightStl)),
            profileId: "apex-v2-insole-95a",
            material: "apex_light",
            fileName: "ApexLight_90A.stl",
        });
        expect(normalizeGcodeForCompare(coreGcode)).toBe(
            normalizeGcodeForCompare(readFileSync(APEX_CORE_GOLDEN, "utf8")),
        );
        expect(normalizeGcodeForCompare(lightGcode)).toBe(
            normalizeGcodeForCompare(readFileSync(APEX_LIGHT_GOLDEN, "utf8")),
        );
    });
});

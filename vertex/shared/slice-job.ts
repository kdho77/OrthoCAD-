/** One token per successful slice. Failure, timeout, and cancellation charge nothing. */
export const SLICE_TOKEN_COST = 1;

/** Client poll and server job budget. A slice still running past this is failed with no charge. */
export const SLICE_TIMEOUT_MS = 10 * 60 * 1000;

export const SLICE_POLL_INITIAL_MS = 2_000;
export const SLICE_POLL_MAX_MS = 10_000;

export type SliceJobStatusName = "queued" | "running" | "succeeded" | "failed";

const VERTEXSLICE_PROFILES = new Set([
    "apex-v2-insole-95a",
    "apex-v2-insole-soft",
    "apex-v2-insole-extra-soft",
    "apex-v2-insole-medium",
    "apex-v2-insole-hard",
    "apex-v2-insole-extra-hard",
]);

const HARDNESS_PROFILE: Record<string, string> = {
    "extra soft": "apex-v2-insole-extra-soft",
    soft: "apex-v2-insole-soft",
    medium: "apex-v2-insole-medium",
    hard: "apex-v2-insole-hard",
    "extra hard": "apex-v2-insole-extra-hard",
};

/** CNC / milled orders are not sliced. */
export function isCncProcess(process: string | null | undefined): boolean {
    if (!process) return false;
    const p = process.trim().toLowerCase();
    return (
        p === "cnc" ||
        p === "mill" ||
        p === "milled" ||
        p === "milling" ||
        p.startsWith("cnc_") ||
        p.startsWith("cnc-") ||
        p.startsWith("mill_") ||
        p.startsWith("mill-") ||
        p.startsWith("milling")
    );
}

export function isVertexSliceProfile(profileId: string | null | undefined): boolean {
    if (!profileId) return false;
    return VERTEXSLICE_PROFILES.has(profileId.trim().toLowerCase());
}

/** Map an OrthoCAD preset / material name onto the VertexSlice `/v1/slice` material id. */
export function mapVertexSliceMaterial(raw: string | null | undefined): string {
    const s = (raw ?? "").trim().toLowerCase();
    if (!s) return "apex_core";
    if (s === "apex_core" || s === "apex_light" || s === "apex_forge" || s === "apex_bounce") return s;
    if (s.includes("light") || s.includes("lite") || s.includes("90a")) return "apex_light";
    if (s.includes("forge")) return "apex_forge";
    if (s.includes("bounce")) return "apex_bounce";
    return "apex_core";
}

/**
 * Profile sent to VertexSlice. Caller profile ids that already match the slicer
 * are passed through; otherwise hardness or the ApexCore 95A baseline is used.
 */
export function resolveVertexSliceTarget(input: {
    profileId?: string | null;
    material?: string | null;
    hardness?: string | null;
}): { profileId: string; material: string } {
    const material = mapVertexSliceMaterial(input.material ?? input.profileId);
    const profileId = input.profileId?.trim().toLowerCase();
    if (profileId && isVertexSliceProfile(profileId)) {
        return { profileId, material };
    }
    const hardnessKey = (input.hardness ?? "").trim().toLowerCase();
    const fromHardness = HARDNESS_PROFILE[hardnessKey];
    return { profileId: fromHardness ?? "apex-v2-insole-95a", material };
}

const GOLDEN_IGNORE = [/^;\s*generated by\b/i, /^;\s*printing object\b/i, /^;\s*stop printing object\b/i];

/**
 * Drop slicer banner and per-object name comments so two G-code files can be
 * compared without committing either file. All other lines stay byte-for-line.
 */
export function normalizeGcodeForCompare(gcode: string): string {
    const lines = gcode.replace(/^\uFEFF/, "").split(/\r?\n/);
    return lines.filter((line) => !GOLDEN_IGNORE.some((re) => re.test(line.trim()))).join("\n");
}

/** Backoff from 2s toward 10s. `attempt` is 0-based. */
export function nextSlicePollDelayMs(attempt: number): number {
    const delay = SLICE_POLL_INITIAL_MS * 1.5 ** Math.max(0, attempt);
    return Math.min(SLICE_POLL_MAX_MS, Math.round(delay));
}
